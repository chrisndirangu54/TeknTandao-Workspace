#!/usr/bin/env python3
"""Tenant-local hotspot anomaly / occupancy modeling.

Inputs are operator-exported signed IoT samples (JSONL); not guest identities.
No router commands or production deployment. Model checkpoints are unsafe to
load from untrusted parties; only load artifacts generated by this pipeline.
"""
from __future__ import annotations
import argparse, json, math
from pathlib import Path
import numpy as np
import pandas as pd
from joblib import dump
from sklearn.ensemble import IsolationForest, HistGradientBoostingRegressor
from sklearn.metrics import mean_absolute_error
from sklearn.preprocessing import RobustScaler
from sklearn.pipeline import Pipeline

FEATURES=["clients","latency_ms","packet_loss","battery_percent","signal_dbm",
          "wan_up","hour_sin","hour_cos","weekday_sin","weekday_cos",
          "clients_lag_1","clients_roll_4"]
MIN_ROWS=200
MIN_DAYS=7

def load_samples(path:Path,site_id:str)->pd.DataFrame:
    if not site_id or any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-" for c in site_id):
        raise ValueError("invalid site ID")
    records=[]
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():continue
        row=json.loads(line)
        if row.get("siteId")!=site_id:continue
        m=row.get("metrics",{})
        if not isinstance(m,dict):continue
        values={"clients":m.get("clientCount"),"latency_ms":m.get("latencyMs"),
                "packet_loss":m.get("packetLossPercent"),
                "battery_percent":m.get("batteryPercent"),
                "signal_dbm":m.get("signalDbm"),"wan_up":m.get("wanUp")}
        if (not isinstance(row.get("observedAtMs"),int)
            or not isinstance(values["clients"],int)
            or not 0<=values["clients"]<=100000):continue
        records.append({"time":pd.to_datetime(row["observedAtMs"],unit="ms",utc=True),
                        **values})
    if not records:raise ValueError("no valid site-scoped telemetry")
    df=pd.DataFrame(records).sort_values("time").drop_duplicates(subset=["time"])
    if len(df)<MIN_ROWS:raise ValueError("at least 200 signed telemetry samples required")
    if df["time"].dt.floor("D").nunique()<MIN_DAYS:raise ValueError("at least seven separate days required")
    for name in ["latency_ms","packet_loss","battery_percent","signal_dbm"]:
        df[name]=pd.to_numeric(df[name],errors="coerce").clip(lower={
            "latency_ms":0,"packet_loss":0,"battery_percent":0,"signal_dbm":-160}[name],
            upper={"latency_ms":600000,"packet_loss":100,"battery_percent":100,"signal_dbm":20}[name])
    df["wan_up"]=df["wan_up"].map({True:1,False:0})
    for name in ["latency_ms","packet_loss","battery_percent","signal_dbm","wan_up"]:
        if df[name].notna().mean()<0.7:
            raise ValueError(f"not enough real observations for {name}")
        df[name]=df[name].ffill(limit=3).fillna(df[name].median())
    hour=df["time"].dt.hour+df["time"].dt.minute/60
    weekday=df["time"].dt.dayofweek
    df["hour_sin"]=np.sin(2*np.pi*hour/24)
    df["hour_cos"]=np.cos(2*np.pi*hour/24)
    df["weekday_sin"]=np.sin(2*np.pi*weekday/7)
    df["weekday_cos"]=np.cos(2*np.pi*weekday/7)
    df["clients_lag_1"]=df["clients"].shift(1)
    df["clients_roll_4"]=df["clients"].shift(1).rolling(4,min_periods=1).mean()
    df["target_next_clients"]=df["clients"].shift(-1)
    df=df.dropna(subset=["clients_lag_1","clients_roll_4","target_next_clients"])
    return df

def train_site_model(df:pd.DataFrame,site_id:str,output:Path)->dict:
    # Chronological holdout prevents future data leakage.
    train_end=int(len(df)*.70);valid_end=int(len(df)*.85)
    if train_end<120 or valid_end-train_end<20 or len(df)-valid_end<20:
        raise ValueError("insufficient chronological training/holdout samples")
    train=df.iloc[:train_end];valid=df.iloc[train_end:valid_end];test=df.iloc[valid_end:]
    # Same-cadence next-observation occupancy forecast. Report cadence, not "next hour".
    cadence_minutes=float(df["time"].diff().dt.total_seconds().median()/60)
    if not 1<=cadence_minutes<=120:raise ValueError("unsupported sampling cadence")
    model=Pipeline([("scale",RobustScaler()),
      ("regressor",HistGradientBoostingRegressor(random_state=44,max_iter=100,max_leaf_nodes=15))])
    model.fit(train[FEATURES],train["target_next_clients"])
    prediction=np.maximum(0,model.predict(test[FEATURES]))
    baseline=test["clients"].to_numpy()
    mae=float(mean_absolute_error(test["target_next_clients"],prediction))
    baseline_mae=float(mean_absolute_error(test["target_next_clients"],baseline))
    # Choose the trained forecast only if it outperforms the naive baseline.
    selected="hist_gradient_boosting" if mae<baseline_mae else "last_observation"
    anomaly=Pipeline([("scale",RobustScaler()),
      ("detector",IsolationForest(n_estimators=150,contamination=0.03,random_state=44))])
    anomaly.fit(train[FEATURES])
    holdout_anomaly_fraction=float(np.mean(anomaly.predict(test[FEATURES])<0))
    output.mkdir(parents=True,exist_ok=True)
    dump({"forecast":model,"anomaly":anomaly,"features":FEATURES,
          "selected_forecast":selected,"site_id":site_id},output/"hotspot_models.joblib")
    report={"siteId":site_id,"rows":len(df),"days":int(df["time"].dt.floor("D").nunique()),
      "samplingCadenceMinutes":cadence_minutes,"holdoutRows":len(test),
      "forecastMaeClients":mae,"lastObservationBaselineMaeClients":baseline_mae,
      "selectedForecast":selected,"holdoutAnomalyFraction":holdout_anomaly_fraction,
      "trainedOn":"site_scoped_signed_iot_export","siteIsolation":True,
      "modelControlsRouters":False,"deployed":False,
      "caveats":["Unsupervised anomaly labels are not ground truth",
       "Model has not been tested against actual router incidents",
       "Load only locally trusted model files; joblib deserialization can execute code",
       "Holdout lacks true drift/retraining monitoring and fairness assessments"]}
    (output/"model_card.json").write_text(json.dumps(report,indent=2),encoding="utf-8")
    return report

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--input",type=Path,required=True)
    parser.add_argument("--site-id",required=True)
    parser.add_argument("--output",type=Path,required=True)
    args=parser.parse_args()
    result=train_site_model(load_samples(args.input,args.site_id),args.site_id,args.output)
    print(json.dumps(result,indent=2))

if __name__=="__main__":main()
